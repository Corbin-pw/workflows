# shellcheck shell=bash
# lib/slurm.sh -- slurm.conf / gres.conf / cgroup.conf generation, shared by
# 04-provision-nodes.sh (Ubuntu apt Slurm) and 04b-slurm-pmix.sh (source-built
# Slurm with PMIx). Source after lib/common.sh.

# Marker written on every node by 04b. Its presence means "Slurm here is the
# source build"; 04 then leaves the Slurm packages alone instead of
# reinstalling the apt ones over it.
TB_SLURM_MARKER="/etc/slurm/.tb-source-build"

tb_slurm_is_source_build() { lxc exec "$CONTROLLER" -- test -f "$TB_SLURM_MARKER" 2>/dev/null; }

tb_slurm_version() {
  lxc exec "$CONTROLLER" -- bash -c 'slurmctld -V 2>/dev/null | awk "{print \$2}"' 2>/dev/null
}

# Does the controller's Slurm have the PMIx MPI plugin? Looked up as a file,
# not with `srun --mpi=list`, because srun needs a working slurm.conf first.
tb_slurm_has_pmix() {
  lxc exec "$CONTROLLER" -- bash -c 'ls /usr/lib/slurm/mpi_pmix*.so /usr/lib/*/slurm*/mpi_pmix*.so 2>/dev/null | grep -q .' 2>/dev/null
}

_tb_gpu_dev_of()  { lxc exec "$1" -- bash -c 'ls /dev/nvidia[0-9]* 2>/dev/null | head -1'; }
_tb_gpu_type_of() { lxc exec "$1" -- nvidia-smi --query-gpu=name --format=csv,noheader 2>/dev/null | head -1 \
                    | sed -E 's/NVIDIA //; s/GeForce //; s/ PCIe//; s/[^A-Za-z0-9]//g' | tr 'A-Z' 'a-z'; }
_tb_mem_mb()      { echo $(( $(numfmt --from=iec "${1%iB}") / 1048576 - 1024 )); }   # leave 1 GiB for the OS

# tb_slurm_configure GENERATOR_NAME
# Writes the three files, pushes them to every node, (re)starts the daemons.
tb_slurm_configure() {
  local gen="${1:-lib/slurm.sh}" stage mpi_default node_lines="" gres_lines="" has_gpu=0 i c gres dev typ
  stage="$(mktemp -d)"

  if tb_slurm_has_pmix; then
    mpi_default="${SLURM_MPI_DEFAULT:-pmix}"
    ok "PMIx plugin present -> MpiDefault=${mpi_default}"
  else
    mpi_default="none"
    ok "no PMIx plugin in this Slurm -> MpiDefault=none (pmi2 still available via srun --mpi=pmi2)"
  fi

  for i in "${!COMPUTES[@]}"; do
    c="${COMPUTES[$i]}"; gres=""
    if [ -n "${GPU_PCI[$i]:-}" ]; then
      dev="$(_tb_gpu_dev_of "$c")"; typ="$(_tb_gpu_type_of "$c")"
      if [ -n "$dev" ] && [ -n "$typ" ]; then
        gres=" Gres=gpu:${typ}:1"; has_gpu=1
        gres_lines+="NodeName=${c} Name=gpu Type=${typ} File=${dev}"$'\n'
        ok "$c: GPU ${typ} at ${dev}"
      else warn "$c: GPU_PCI set but no /dev/nvidiaN or nvidia-smi inside the node -- no gres"; fi
    fi
    node_lines+="NodeName=${c} NodeAddr=${COMPUTE_IPS[$i]} CPUs=${SLURM_COMPUTE_CPUS:-$COMPUTE_CPUS} RealMemory=$(_tb_mem_mb "$COMPUTE_MEM")${gres} State=UNKNOWN"$'\n'
  done

  cat > "$stage/slurm.conf" <<CONF
# slurm.conf -- ${CLUSTER_NAME} testbed, generated by ${gen} $(date -I)
# Slurm $(tb_slurm_version || echo '?')$(tb_slurm_is_source_build && echo ' (source build, see 04b-slurm-pmix.sh)' || echo ' (Ubuntu apt)')
ClusterName=${CLUSTER_NAME}
SlurmctldHost=${CONTROLLER}(${CONTROLLER_IP})
AuthType=auth/munge
SlurmUser=slurm
StateSaveLocation=/var/lib/slurm/slurmctld
SlurmdSpoolDir=/var/lib/slurm/slurmd
SlurmctldLogFile=/var/log/slurm/slurmctld.log
SlurmdLogFile=/var/log/slurm/slurmd.log
SlurmctldPidFile=/run/slurmctld.pid
SlurmdPidFile=/run/slurmd.pid
ReturnToService=2
# --- testbed deviations (system containers) -------------------------------
# cgroup-based tracking/confinement inside an unprivileged LXD container is
# fragile, so jobs are tracked by process tree and not CPU/device confined.
# Production most likely uses proctrack/cgroup + task/cgroup,task/affinity.
ProctrackType=proctrack/linuxproc
TaskPlugin=task/none
# Trust the CPU/memory below instead of hwloc, which can see all host threads
# through the container's /sys rather than the limits.cpu share.
SlurmdParameters=config_overrides
# --------------------------------------------------------------------------
SchedulerType=sched/backfill
SelectType=select/cons_tres
SelectTypeParameters=CR_CPU_Memory
DefMemPerCPU=2048
MpiDefault=${mpi_default}
# No accounting (slurmdbd) -- the defaults, stated by omission so the same file
# is valid for both 21.08 and current Slurm.
$( [ "$has_gpu" = 1 ] && echo "GresTypes=gpu" )
# --- nodes ----------------------------------------------------------------
${node_lines}PartitionName=${SLURM_PARTITION} Nodes=ALL Default=YES MaxTime=INFINITE State=UP
CONF
  printf '%s' "$gres_lines" > "$stage/gres.conf"
  # Current Slurm loads a cgroup plugin in slurmd even with the non-cgroup
  # proctrack/task plugins above; inside a container that can fail, so turn it
  # off explicitly. 21.08 (apt) does not know "disabled" -- no file there.
  if tb_slurm_is_source_build; then printf 'CgroupPlugin=disabled\n' > "$stage/cgroup.conf"; fi

  sed 's/^/  | /' "$stage/slurm.conf"
  [ -s "$stage/gres.conf" ]   && sed 's/^/  gres   | /' "$stage/gres.conf"
  [ -f "$stage/cgroup.conf" ] && sed 's/^/  cgroup | /' "$stage/cgroup.conf"
  cp "$stage/"*.conf "$HOST_BASE/"   # keep copies for the write-up

  local n
  for n in "${ALL_NODES[@]}"; do
    nexec "$n" "mkdir -p /etc/slurm"
    lxc file push "$stage/slurm.conf" "$n/etc/slurm/slurm.conf"
    lxc file push "$stage/gres.conf"  "$n/etc/slurm/gres.conf"
    if [ -f "$stage/cgroup.conf" ]; then lxc file push "$stage/cgroup.conf" "$n/etc/slurm/cgroup.conf"
    else nexec "$n" "rm -f /etc/slurm/cgroup.conf"; fi
    nexec "$n" "mkdir -p /var/lib/slurm/slurmctld /var/lib/slurm/slurmd /var/log/slurm && chown -R slurm:slurm /var/lib/slurm /var/log/slurm && chmod 644 /etc/slurm/*.conf"
  done
  rm -rf "$stage"

  say "Starting Slurm"
  nexec "$CONTROLLER" "systemctl daemon-reload; systemctl enable slurmctld >/dev/null 2>&1; systemctl restart slurmctld"
  for c in "${COMPUTES[@]}"; do nexec "$c" "systemctl daemon-reload; systemctl enable slurmd >/dev/null 2>&1; systemctl restart slurmd"; done
  sleep 5
  nexec "$CONTROLLER" "scontrol update nodename=$(IFS=,; echo "${COMPUTES[*]}") state=resume 2>/dev/null || true; sinfo -N -l"
}
